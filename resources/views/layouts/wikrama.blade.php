    <script>
        document.addEventListener('DOMContentLoaded', function() {
            var navEl = document.getElementById('wrapper-navbar');
            var lastScrollY = window.pageYOffset || document.documentElement.scrollTop;
            var scrollThreshold = 10;

            function handleNavbarScroll() {
                if (!navEl) return;
                var currentScrollY = window.pageYOffset || document.documentElement.scrollTop;

                if (currentScrollY <= 80) {
                    navEl.classList.add('nav-at-top');
                    navEl.classList.remove('nav-hidden', 'nav-visible', 'uicore-scrolled');
                    lastScrollY = currentScrollY;
                    return;
                }

                var diff = currentScrollY - lastScrollY;
                if (Math.abs(diff) < scrollThreshold) {
                    return;
                }

                if (diff > 0) {
                    // Scrolling DOWN -> HILANG (Hide completely)
                    navEl.classList.remove('nav-at-top', 'nav-visible');
                    navEl.classList.add('nav-hidden');
                } else {
                    // Scrolling UP -> BARU MUNCUL (Show with solid white & visible dark text)
                    navEl.classList.remove('nav-at-top', 'nav-hidden');
                    navEl.classList.add('nav-visible', 'uicore-scrolled');
                }

                lastScrollY = currentScrollY <= 0 ? 0 : currentScrollY;
            }
            window.addEventListener('scroll', handleNavbarScroll, { passive: true });
            handleNavbarScroll();
        });
    </script>

